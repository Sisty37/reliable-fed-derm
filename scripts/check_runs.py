def group(r):
    d, t = r.split("/")
    if d == "split_official":
        return "E0  official split"
    if d == "e0b":
        return "E0b replication arms"
    if d == "padufes20":
        return "E6  PAD-UFES-20 predictions"
    if d.startswith("sibexp"):
        return "E8  sibling-exposure crossover"
    if "mlp" in t:
        return "E9  two-layer heads (model B)"
    if "loco" in t:
        return "E6  leave-one-client-out"
    if t.startswith("effb0frozen"):
        return "E1  A-frozen"
    if t.startswith("pandermfrozen"):
        return "E1/E2/E7  model B"
    return "E1/E2/E7  model A"


def main():
    groups = {}
    for r in RUNS:
        p = os.path.join("runs", *r.split("/"))
        ok = os.path.exists(os.path.join(p, "preds.npz")) and os.path.exists(os.path.join(p, "metrics.json"))
        if r.startswith("padufes20"):
            ok = os.path.exists(os.path.join(p, "preds.npz"))
        groups.setdefault(group(r), []).append((r, ok))
    total_missing = 0
    print("=== Training runs ===")
    for g in sorted(groups):
        rs = groups[g]
        miss = [r for r, ok in rs if not ok]
        total_missing += len(miss)
        print(f"  {g:34s} {len(rs) - len(miss):4d} / {len(rs):4d}  {'OK' if not miss else 'MISSING ' + str(len(miss))}")
        for r in miss[:20]:
            print(f"      missing: runs/{r}")
        if len(miss) > 20:
            print(f"      ... and {len(miss) - 20} more")
    print("=== Result files ===")
    miss_res = [f for f in RESULTS if not os.path.exists(os.path.join("results", f))]
    print(f"  results/*.json  {len(RESULTS) - len(miss_res)} / {len(RESULTS)}  {'OK' if not miss_res else 'MISSING'}")
    for f in miss_res:
        print(f"      missing: results/{f}")
    print("=== Other inputs ===")
    for f in EXTRA:
        print(f"  {f:34s} {'OK' if os.path.exists(f) else 'MISSING'}")
    print()
    if total_missing == 0 and not miss_res:
        print("ALL DONE: every run and result file used by the paper is present.")
    else:
        print(f"NOT COMPLETE: {total_missing} runs and {len(miss_res)} result files missing (see above).")


if __name__ == "__main__":
    main()
